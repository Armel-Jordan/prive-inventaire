    /**
     * Comptes d'un plan type, prêts à créer, dans l'ordre (un parent avant ses sous-comptes).
     *
     * @return list<array{numero: string, libelle: string, nature: string, type: string, parent: ?string, saisie_manuelle: bool}>
     */
    public static function comptes(string $plan): array
    {
        $lignes = match ($plan) {
            'syscohada' => self::syscohada(),
            'pcg' => self::pcg(),
            'canadien' => self::canadien(),
        };
        $numeros = array_map(fn (array $l) => $l[0], $lignes);

        return array_map(function (array $ligne) use ($plan, $numeros) {
            [$numero, $libelle, $nature] = $ligne;
            $type = $ligne[3] ?? ($plan === 'canadien'
                ? (preg_match('/^\d0000$/', $numero) ? 'en_tete' : 'standard')
                : (strlen($numero) <= 2 ? 'en_tete' : 'standard'));

            return [
                'numero' => $numero,
                'libelle' => $libelle,
                'nature' => $nature,
                'type' => $type,
                'parent' => self::parentDe($numero, $numeros, $plan === 'canadien'),
                'saisie_manuelle' => $type !== 'en_tete',
            ];
        }, $lignes);
    }

    /**
     * Parent d'un numéro parmi une liste de numéros : le plus long numéro qui en est un préfixe strict (401 sous
     * 40, 40 sous 4). Plan à 5 chiffres : l'en-tête de la classe (10100 sous 10000), sauf pour l'en-tête lui-même.
     *
     * @param  list<string>  $numeros
     */
    public static function parentDe(string $numero, array $numeros, bool $cinqChiffres = false): ?string
    {
        if ($cinqChiffres) {
            $entete = $numero[0].'0000';

            return $entete !== $numero && in_array($entete, $numeros, true) ? $entete : null;
        }
        for ($longueur = strlen($numero) - 1; $longueur > 0; $longueur--) {
            $prefixe = substr($numero, 0, $longueur);
            if (in_array($prefixe, $numeros, true)) {
                return $prefixe;
            }
        }

        return null;
    }

